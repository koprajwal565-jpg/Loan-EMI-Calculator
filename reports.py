def generate_amortization_pdf(calc_data, schedule, output_path=None):
    """
    Generate a publication-grade PDF report with loan summary, chart,
    and complete month-by-month amortization schedule.
    
    Returns:
        bytes: Raw PDF content.
        Also writes to output_path if provided.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        output_path if output_path else buffer,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=50,
        bottomMargin=55
    )
    
    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1E3A8A')
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#64748B')
    )
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=17,
        textColor=colors.HexColor('#0F172A'),
        spaceBefore=14,
        spaceAfter=8
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#334155')
    )
    
    elements = []
    
    # 1. Header Banner
    elements.append(Paragraph("SmartLoan Financial Report", title_style))
    elements.append(Paragraph(
        f"Loan EMI Calculation & Amortization Repayment Schedule | Generated: {datetime.now().strftime('%B %d, %Y, %I:%M %p')}",
        subtitle_style
    ))
    elements.append(Spacer(1, 15))
    
    # 2. Executive Loan Summary Table
    elements.append(Paragraph("Loan Summary Overview", section_heading))
    
    summary_data = [
        [
            Paragraph("<b>Loan Type:</b>", body_style),
            Paragraph(str(calc_data.get('loan_type', 'Personal Loan')), body_style),
            Paragraph("<b>Monthly EMI:</b>", body_style),
            Paragraph(f"<b><font color='#2563EB'>Rs. {calc_data['monthly_emi']:,.2f}</font></b>", body_style)
        ],
        [
            Paragraph("<b>Loan Principal:</b>", body_style),
            Paragraph(f"Rs. {calc_data['loan_amount']:,.2f}", body_style),
            Paragraph("<b>Total Interest:</b>", body_style),
            Paragraph(f"<font color='#D97706'>Rs. {calc_data['total_interest']:,.2f}</font>", body_style)
        ],
        [
            Paragraph("<b>Annual Interest Rate:</b>", body_style),
            Paragraph(f"{calc_data['annual_interest_rate']:.2f}% p.a.", body_style),
            Paragraph("<b>Total Repayment:</b>", body_style),
            Paragraph(f"<b>Rs. {calc_data['total_payment']:,.2f}</b>", body_style)
        ],
        [
            Paragraph("<b>Tenure:</b>", body_style),
            Paragraph(f"{calc_data['tenure_months']} Months ({calc_data.get('tenure_years', round(calc_data['tenure_months']/12, 1))} Years)", body_style),
            Paragraph("<b>Interest Ratio:</b>", body_style),
            Paragraph(f"{calc_data.get('interest_pct', 0.0):.1f}% of repayment", body_style)
        ]
    ]
    
    summary_table = Table(summary_data, colWidths=[120, 145, 120, 145])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#E2E8F0')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 15))
    
    # 3. Insert Matplotlib Pie Chart Image
    chart_temp = os.path.join(tempfile.gettempdir(), f"pie_chart_{datetime.now().timestamp()}.png")
    generate_pie_chart(calc_data['loan_amount'], calc_data['total_interest'], output_path=chart_temp)
    if os.path.exists(chart_temp):
        elements.append(Image(chart_temp, width=380, height=210))
        elements.append(Spacer(1, 10))
        
    elements.append(PageBreak())
    
    # 4. Amortization Schedule Table
    elements.append(Paragraph("Detailed Amortization Repayment Schedule", section_heading))
    elements.append(Paragraph(
        "All values are in Indian Rupees (Rs.). Repayments assume standard monthly reducing balance compounding.",
        subtitle_style
    ))
    elements.append(Spacer(1, 10))
    
    table_header = ["Month", "Opening Bal (Rs)", "EMI (Rs)", "Principal (Rs)", "Interest (Rs)", "Closing Bal (Rs)"]
    table_rows = [table_header]
    
    for row in schedule:
        table_rows.append([
            str(row['month']),
            f"{row['opening_balance']:,.2f}",
            f"{row['emi']:,.2f}",
            f"{row['principal_paid']:,.2f}",
            f"{row['interest_paid']:,.2f}",
            f"{row['closing_balance']:,.2f}"
        ])
        
    col_widths = [50, 96, 96, 96, 96, 96]
    amort_table = Table(table_rows, colWidths=col_widths, repeatRows=1)
    
    amort_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1E3A8A')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 8),
        ('ALIGN', (0, 0), (0, -1), 'CENTER'),
        ('ALIGN', (1, 0), (-1, -1), 'RIGHT'),
        ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 1), (-1, -1), 8),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
    ]
    
    # Alternating row colors
    for r in range(1, len(table_rows)):
        if r % 2 == 0:
            amort_style.append(('BACKGROUND', (0, r), (-1, r), colors.HexColor('#F8FAFC')))
            
    amort_table.setStyle(TableStyle(amort_style))
    elements.append(amort_table)
    
    # Build Document using NumberedCanvas
    doc.build(elements, canvasmaker=NumberedCanvas)
    
    # Clean up temporary chart file
    if os.path.exists(chart_temp):
        try:
            os.remove(chart_temp)
        except OSError:
            pass
            
    if output_path:
        with open(output_path, 'rb') as f:
            return f.read()
            
    buffer.seek(0)
    return buffer.getvalue()
