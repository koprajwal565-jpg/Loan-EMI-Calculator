def generate_amortization_csv(calc_data, schedule):
    """
    Generate CSV content for loan amortization schedule using Python's csv module.
    
    Returns:
        str: Comma-separated CSV text.
    """
    output = io.StringIO()
    writer = csv.writer(output)
    
    # Metadata Header
    writer.writerow(["SmartLoan - Loan EMI & Amortization Repayment Schedule"])
    writer.writerow(["Generated At", datetime.now().strftime("%Y-%m-%d %H:%M:%S")])
    writer.writerow(["Loan Type", calc_data.get('loan_type', 'N/A')])
    writer.writerow(["Loan Principal (Rs)", f"{calc_data['loan_amount']:.2f}"])
    writer.writerow(["Annual Interest Rate (%)", f"{calc_data['annual_interest_rate']:.2f}"])
    writer.writerow(["Loan Tenure (Months)", calc_data['tenure_months']])
    writer.writerow(["Loan Tenure (Years)", f"{calc_data.get('tenure_years', calc_data['tenure_months']/12.0):.2f}"])
    writer.writerow(["Monthly EMI (Rs)", f"{calc_data['monthly_emi']:.2f}"])
    writer.writerow(["Total Interest Payable (Rs)", f"{calc_data['total_interest']:.2f}"])
    writer.writerow(["Total Repayment Amount (Rs)", f"{calc_data['total_payment']:.2f}"])
    writer.writerow([])
    
    # Amortization Table Headers
    writer.writerow([
        "Month Number",
        "Opening Balance (Rs)",
        "Monthly EMI (Rs)",
        "Principal Component (Rs)",
        "Interest Component (Rs)",
        "Closing Balance (Rs)"
    ])
    
    # Amortization Rows
    for row in schedule:
        writer.writerow([
            row['month'],
            f"{row['opening_balance']:.2f}",
            f"{row['emi']:.2f}",
            f"{row['principal_paid']:.2f}",
            f"{row['interest_paid']:.2f}",
            f"{row['closing_balance']:.2f}"
        ])
        
    return output.getvalue()


