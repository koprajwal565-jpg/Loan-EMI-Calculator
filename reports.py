def generate_pie_chart(principal, total_interest, output_path=None):
    """
    Generate an elegant Donut/Pie Chart comparing Principal vs Interest.
    
    Returns:
        str: Base64 data URI string for embedding directly in HTML <img> tags.
        Also saves to output_path if provided.
    """
    # Create figure with high DPI for crisp rendering
    fig, ax = plt.subplots(figsize=(6, 4.2), dpi=150)
    
    labels = ['Principal Loan Amount', 'Total Interest Payable']
    values = [float(principal), float(total_interest)]
    
    # Modern professional colors: Navy/Blue for Principal, Coral/Amber for Interest
    chart_colors = ['#1E3A8A', '#F59E0B']
    
    # Format labels with monetary values
    legend_labels = [
        f"Principal: ₹{principal:,.2f}",
        f"Total Interest: ₹{total_interest:,.2f}"
    ]
    
    wedges, texts, autotexts = ax.pie(
        values,
        labels=None,
        autopct='%1.1f%%',
        startangle=140,
        colors=chart_colors,
        pctdistance=0.72,
        wedgeprops=dict(width=0.45, edgecolor='white', linewidth=2.5)
    )
    
    # Style percentage text inside donut slices
    for autotext in autotexts:
        autotext.set_color('white')
        autotext.set_fontsize(11)
        autotext.set_weight('bold')
        
    ax.legend(
        wedges,
        legend_labels,
        title="Breakdown",
        loc="center left",
        bbox_to_anchor=(1, 0, 0.5, 1),
        frameon=False,
        fontsize=9,
        title_fontsize=10
    )
    
    ax.set_title("Principal vs. Total Interest Breakdown", fontsize=13, fontweight='bold', pad=15, color='#0F172A')
    plt.tight_layout()
    
    # Save to file if path specified
    if output_path:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        plt.savefig(output_path, format='png', bbox_inches='tight', dpi=150)
        
    # Return Base64 encoded string for HTML rendering
    buf = io.BytesIO()
    plt.savefig(buf, format='png', bbox_inches='tight', dpi=150)
    plt.close(fig)
    buf.seek(0)
    b64_str = base64.b64encode(buf.getvalue()).decode('utf-8')
    return f"data:image/png;base64,{b64_str}"


def generate_comparison_chart(loans_data, output_path=None):
    """
    Generate a grouped bar chart comparing Monthly EMI, Total Principal,
    and Total Interest across up to three loan offers.
    
    Returns:
        str: Base64 data URI string.
    """
    import numpy as np
    
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4.5), dpi=150)
    
    labels = [l.get('label', f"Option {i+1}") for i, l in enumerate(loans_data)]
    emis = [float(l['monthly_emi']) for l in loans_data]
    principals = [float(l['loan_amount']) for l in loans_data]
    interests = [float(l['total_interest']) for l in loans_data]
    
    x = np.arange(len(labels))
    bar_width = 0.5
    
    # Subplot 1: Monthly EMI comparison
    bars1 = ax1.bar(x, emis, width=bar_width, color='#2563EB', edgecolor='#1D4ED8', alpha=0.9)
    ax1.set_title("Monthly EMI Comparison (₹)", fontsize=11, fontweight='bold', color='#0F172A')
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels, fontsize=9)
    ax1.grid(axis='y', linestyle='--', alpha=0.4)
    ax1.set_axisbelow(True)
    
    # Add values on top of bars
    for bar in bars1:
        yval = bar.get_height()
        ax1.text(bar.get_x() + bar.get_width() / 2, yval * 1.01, f"₹{yval:,.0f}",
                 ha='center', va='bottom', fontsize=8, fontweight='bold')
                 
    # Subplot 2: Stacked Principal + Interest Comparison
    bars_p = ax2.bar(x, principals, width=bar_width, label='Principal', color='#1E3A8A')
    bars_i = ax2.bar(x, interests, width=bar_width, bottom=principals, label='Total Interest', color='#F59E0B')
    
    ax2.set_title("Total Repayment Breakdown (₹)", fontsize=11, fontweight='bold', color='#0F172A')
    ax2.set_xticks(x)
    ax2.set_xticklabels(labels, fontsize=9)
    ax2.legend(loc='upper left', frameon=True, fontsize=8)
    ax2.grid(axis='y', linestyle='--', alpha=0.4)
    ax2.set_axisbelow(True)
    
    # Add total amount label on top of stacked bars
    for i, (p, intr) in enumerate(zip(principals, interests)):
        total = p + intr
        ax2.text(x[i], total * 1.01, f"₹{total:,.0f}", ha='center', va='bottom', fontsize=8, fontweight='bold')
        
    plt.tight_layout()
    
    if output_path:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        plt.savefig(output_path, format='png', bbox_inches='tight', dpi=150)
        
    buf = io.BytesIO()
    plt.savefig(buf, format='png', bbox_inches='tight', dpi=150)
    plt.close(fig)
    buf.seek(0)
    b64_str = base64.b64encode(buf.getvalue()).decode('utf-8')
    return f"data:image/png;base64,{b64_str}"


