class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print 'Page X of Y' on all pages.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header line & title (skip on page 1 for cleaner cover appearance if desired, or show on all)
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(40, 800, 555, 800)
        self.drawString(40, 805, "SmartLoan Repayment Report | Financial Planning")
        
        # Footer
        self.line(40, 45, 555, 45)
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(555, 32, footer_text)
        self.drawString(40, 32, "Confidential | Generated by SmartLoan College Project")
        self.restoreState()


